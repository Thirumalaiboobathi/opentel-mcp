function step(s) {
  return { source: s.pattern.source, flags: s.pattern.flags, replacement: s.replacement };
}

/** Regex literals / Set literals that core keeps module-private are read out of the source text. */
const CLASSIFY_FILES = ['validation', 'timeout', 'network', 'auth', 'dependency', 'serialization'];

export function extractPrivateRegexes() {
  const out = {};
  const files = CLASSIFY_FILES.map((n) => ['classify/' + n + '.js', path.join(CORE_ROOT, 'src/fingerprint/classify', n + '.js')]);
  files.push(['classify/channel.js', path.join(CORE_ROOT, 'src/fingerprint/classify/channel.js')]);
  for (const [label, file] of files) {
    const text = readFileSync(file, 'utf8');
    // /literal/flags on the right-hand side of a top-level `const X_RE =`
    const re = /^const (\w+_RE) =\s*\n?\s*\/((?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\\\n[])+)\/([a-z]*);/gm;
    let m;
    while ((m = re.exec(text))) {
      const rx = new RegExp(m[2], m[3]);
      out[`${label}#${m[1]}`] = { source: rx.source, flags: rx.flags };
    }
  }
  return out;
}

export function extractClassifierTables() {
  const out = {};
  for (const n of CLASSIFY_FILES) {
    const file = path.join(CORE_ROOT, 'src/fingerprint/classify', n + '.js');
    const text = readFileSync(file, 'utf8');
    const re = /^const (KNOWN_\w+) = new Set\((\[[\s\S]*?\])\);/gm;
    let m;
    while ((m = re.exec(text))) {
      out[`${n}#${m[1]}`] = Function(`"use strict"; return (${m[2]});`)();
    }
    const pre = /^const (KNOWN_PREFIXES) = (\[[\s\S]*?\]);/gm;
    while ((m = pre.exec(text))) {
      out[`${n}#${m[1]}`] = Function(`"use strict"; return (${m[2]});`)();
    }
  }
  return out;
}

