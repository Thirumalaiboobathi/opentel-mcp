/** Runs a throwing handler through the real instrumentMcpServer() and reports the exception event. */
export async function recordedException(mode, spec) {
  const exporter = new InMemorySpanExporter();
  const provider = new NodeTracerProvider({ spanProcessors: [new SimpleSpanProcessor(exporter)] });
  provider.register({ contextManager: null, propagator: null });
  try {
    const server = new Server({ name: 's', version: '0.0.0' }, { capabilities: { tools: {} } });
    instrumentMcpServer(server, { serviceName: 'svc', errorRecording: { mode } });
    server.setRequestHandler(CallToolRequestSchema, async () => {
      const e = new Error(spec.message);
      e.name = spec.name;
      // A real V8 stack would make the fixture machine-dependent, so the stack is always pinned.
      e.stack = spec.stack ?? undefined;
      if (spec.code !== undefined) e.code = spec.code;
      throw e;
    });
    const handler = server._requestHandlers.get('tools/call');
    await handler({ method: 'tools/call', params: { name: 'echo', arguments: {} } }, { requestId: 1 }).catch(() => {});
    const [span] = exporter.getFinishedSpans();
    const ev = span.events.find((e) => e.name === 'exception');
    const out = {
      eventAttributes: ev ? { ...ev.attributes } : null,
      statusCode: span.status.code === SpanStatusCode.ERROR ? 'ERROR' : String(span.status.code),
      statusMessage: span.status.message ?? null,
      errorType: span.attributes['error.type'],
    };
    return out;
  } finally {
    await provider.shutdown();
    trace.disable();
    context.disable();
  }
}

const ER_STACK = 'Error: boom\n    at handler (/srv/app/src/tool.js:10:5)\n    at run (node:internal/x.js:1:1)';

