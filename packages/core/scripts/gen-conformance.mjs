export function serialize(obj) {
  return JSON.stringify(obj, null, 2) + '\n';
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await buildAll();
  let dirty = false;
  for (const [rel, obj] of Object.entries(files)) {
    const file = path.join(CONFORMANCE_DIR, rel);
    const text = serialize(obj);
    if (check) {
      let current = '';
      try {
        current = readFileSync(file, 'utf8');
      } catch {}
      if (current !== text) {
        dirty = true;
        console.error(`conformance: ${rel} is out of date`);
      }
    } else {
      writeFileSync(file, text);
      console.log(`wrote ${path.relative(process.cwd(), file)}`);
    }
  }
  if (check && dirty) {
    console.error('Run: node packages/core/scripts/gen-conformance.mjs');
    process.exit(1);
  }
}

