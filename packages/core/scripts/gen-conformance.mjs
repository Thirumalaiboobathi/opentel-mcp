const CORE_METRIC_NAMES = ['mcp.tool.calls', 'mcp.tool.errors', 'mcp.tool.silent_failures', 'mcp.tool.duration'];

export async function buildContract() {
  const reader = new TestMetricReader();
  const provider = new MeterProvider({ readers: [reader] });
  metrics.setGlobalMeterProvider(provider);
  let found;
  try {
    const rec = setupMeter('0.0.0');
    // every label variant: with and without the optional category
    rec.recordCall('t');
    rec.recordError('t', 'Error', 'internal');
    rec.recordError('t', 'Error');
    rec.recordSilentFailure('t', 'internal');
    rec.recordSilentFailure('t');
    rec.recordDuration('t', 1, 'silent_failure', 'internal');
    rec.recordDuration('t', 1, 'success');
    const { resourceMetrics } = await reader.collect();
    found = resourceMetrics.scopeMetrics;
  } finally {
    await provider.shutdown();
    metrics.disable();
  }
  const scopeNames = new Set(found.map((s) => s.scope.name));
  if (scopeNames.size !== 1) throw new Error('expected one meter scope, got ' + [...scopeNames]);
  const [scopeName] = scopeNames;

  const all = found.flatMap((s) => s.metrics);
  const metricList = CORE_METRIC_NAMES.map((name) => {
    const m = all.find((x) => x.descriptor.name === name);
    if (!m) throw new Error('metric not registered: ' + name);
    const keySets = m.dataPoints.map((dp) => Object.keys(dp.attributes).sort());
    const required = keySets.reduce((acc, ks) => acc.filter((k) => ks.includes(k)));
    const union = [...new Set(keySets.flat())].sort();
    return {
      name,
      kind: String(m.descriptor.type).toLowerCase(),
      unit: m.descriptor.unit ?? '',
      description: m.descriptor.description,
      labelKeys: required,
      optionalLabelKeys: union.filter((k) => !required.includes(k)),
    };
  });

  return {
    schema: 1,
    note: 'Generated by packages/core/scripts/gen-conformance.mjs from the live core exports. Do not edit by hand.',
    contract: `core ${CORE_VERSION}`,
    instrumentationScope: scopeName,
    span: {
      name: { method: attrs.MCP_METHOD_NAME_TOOLS_CALL, template: 'tools/call <tool>', kind: 'SERVER' },
      attributes: {
        methodName: attrs.ATTR_MCP_METHOD_NAME,
        genAiOperationName: attrs.ATTR_GEN_AI_OPERATION_NAME,
        genAiToolName: attrs.ATTR_GEN_AI_TOOL_NAME,
        toolArgumentCount: attrs.ATTR_MCP_TOOL_ARGUMENT_COUNT,
        jsonrpcRequestId: attrs.ATTR_JSONRPC_REQUEST_ID,
        errorType: attrs.ATTR_ERROR_TYPE,
      },
      fingerprintAttributes: { ...fpAttrs.ATTRIBUTE_KEYS },
      values: {
        methodName: attrs.MCP_METHOD_NAME_TOOLS_CALL,
        operationName: attrs.GEN_AI_OPERATION_NAME_EXECUTE_TOOL,
        toolErrorType: attrs.ERROR_TYPE_TOOL_ERROR,
        outcomes: {
          success: attrs.MCP_TOOL_OUTCOME_SUCCESS,
          error: attrs.MCP_TOOL_OUTCOME_ERROR,
          silentFailure: attrs.MCP_TOOL_OUTCOME_SILENT_FAILURE,
        },
        isErrorOrigin: 'tool_error',
        thrownOrigin: 'thrown',
        isErrorClass: 'MCPToolError',
      },
      /** attribute keys core sets on the tools/call span that the Python port defers (ADR 028 Decision 2) */
      deferredInPython: [fpAttrs.ATTRIBUTE_KEYS.VALIDATION_PATHS],
    },
    metrics: metricList,
    allowlists: {
      metricSafeAttributes: [...attrs.METRIC_SAFE_ATTRIBUTES],
      fingerprintMetricSafeAttributes: [...fpAttrs.METRIC_SAFE_ATTRIBUTES],
    },
    failure: {
      categories: ['validation', 'timeout', 'network', 'auth', 'dependency', 'serialization', 'internal', 'unknown'],
      channels: ['execution', 'protocol.not_found', 'protocol.input', 'protocol.output', 'protocol.other', 'unknown'],
      hashVersion: 'v1',
      fallbackFingerprint: '0000000000000000',
      fallbackSignature: 'unfingerprintable',
    },
    errorRecording: {
      modes: ['full', 'normalized', 'none'],
      defaultMode: 'full',
      envVar: 'OTEL_MCP_ERROR_RECORDING_MODE',
      maxErrorClassLength: MAX_ERROR_CLASS_LENGTH,
      maxNormalizeInputLength: MAX_INPUT_LENGTH,
      maxFullMessageLength: MAX_FULL_EXCEPTION_MESSAGE_LENGTH,
      maxFullStackLength: MAX_FULL_EXCEPTION_STACK_LENGTH,
      truncationMarker: ' …[truncated by opentel-mcp]',
    },
  };
}

